    private void BtnRegistrarEquipoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnRegistrarEquipoActionPerformed
                                     
        String codigo = LblCodigo.getText().trim().toUpperCase();
        String tipo = (String) BoxTipo.getSelectedItem();
        String descripcion = LblDescripcion.getText().trim();

        // Validaciones
        if (codigo.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Debes ingresar un código para el equipo.",
                    "Campo vacío", javax.swing.JOptionPane.WARNING_MESSAGE);
            LblCodigo.requestFocus();
            return;
        }
        if (tipo == null || tipo.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Debes seleccionar un tipo de equipo.",
                    "Campo vacío", javax.swing.JOptionPane.WARNING_MESSAGE);
            BoxTipo.requestFocus();
            return;
        }
        
        if (descripcion.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Debes ingresar una descripción para el equipo.",
                    "Campo vacío", javax.swing.JOptionPane.WARNING_MESSAGE);
            LblDescripcion.requestFocus();
            return;
        }
  
        if (EquipoCSV.existeCodigo(codigo)) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Ya existe un equipo con el código \"" + codigo + "\".\nIngresa un código distinto.",
                    "Código duplicado", javax.swing.JOptionPane.ERROR_MESSAGE);
            LblCodigo.requestFocus();
            LblCodigo.selectAll();
            return;
        }

        // Crear y guardar
        Equipo nuevo = new Equipo(codigo, tipo, descripcion, "Disponible");
        boolean ok = EquipoCSV.guardarEquipo(nuevo);

        if (ok) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Equipo registrado correctamente.\nQueda marcado como Disponible.",
                    "Éxito", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            // Limpiar formulario
            LblCodigo.setText("");
            LblDescripcion.setText("");
            BoxTipo.setSelectedIndex(0);
            LblCodigo.requestFocus();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "No se pudo guardar el equipo. Revisa la consola para más detalles.",
                    "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }                              
    }//GEN-LAST:event_BtnRegistrarEquipoActionPerformed

