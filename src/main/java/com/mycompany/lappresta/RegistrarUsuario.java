    private void BtnRegistrarUsuarioActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnRegistrarUsuarioActionPerformed
                               
        String cedula = LblCedula.getText().trim();
        String tipo = (String) BoxTipoUsuario.getSelectedItem();
        String nombre = LblNombres.getText().trim();
        String telefono = LblNumeroTelefono.getText().trim();

        // --- Validaciones ---
        if (cedula.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Debes ingresar la cédula.", "Campo vacío",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            LblCedula.requestFocus();
            return;
        }
        if (!cedula.matches("\\d{10}")) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "La cédula debe tener exactamente 10 números.",
                    "Cédula inválida", javax.swing.JOptionPane.ERROR_MESSAGE);
            LblCedula.requestFocus();
            LblCedula.selectAll();
            return;
        }
        if (tipo == null || tipo.trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Debes seleccionar un tipo (Docente o Estudiante).",
                    "Campo vacío", javax.swing.JOptionPane.WARNING_MESSAGE);
            BoxTipoUsuario.requestFocus();
            return;
        }
        if (nombre.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Debes ingresar el nombre completo.", "Campo vacío",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            LblNombres.requestFocus();
            return;
        }
        if (telefono.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Debes ingresar el número de teléfono.", "Campo vacío",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            LblNumeroTelefono.requestFocus();
            return;
        }
        if (!telefono.matches("09\\d{8}")) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "El teléfono debe tener 10 dígitos y empezar por 09.\nEjemplo: 0912345678",
                    "Teléfono inválido", javax.swing.JOptionPane.ERROR_MESSAGE);
            LblNumeroTelefono.requestFocus();
            LblNumeroTelefono.selectAll();
            return;
        }
        if (UsuarioCSV.existeCedula(cedula)) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Ya existe un usuario con la cédula " + cedula + ".",
                    "Cédula duplicada", javax.swing.JOptionPane.ERROR_MESSAGE);
            LblCedula.requestFocus();
            LblCedula.selectAll();
            return;
        }

        // --- Guardar ---
        Usuario nuevo = new Usuario(cedula, nombre, tipo, telefono);
        boolean ok = UsuarioCSV.guardarUsuario(nuevo);

        if (ok) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Usuario registrado correctamente como " + tipo + ".",
                    "Éxito", javax.swing.JOptionPane.INFORMATION_MESSAGE);
            LblCedula.setText("");
            LblNombres.setText("");
            LblNumeroTelefono.setText("");
            BoxTipoUsuario.setSelectedIndex(0);
            LblCedula.requestFocus();
            actualizarTablaUsuarios("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "No se pudo guardar el usuario. Revisa la consola.",
                    "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }                                                
    }//GEN-LAST:event_BtnRegistrarUsuarioActionPerformed

